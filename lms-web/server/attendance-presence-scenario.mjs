import assert from 'node:assert/strict';
import { randomUUID } from 'node:crypto';
import { createAttendancePresence } from './attendance-presence.mjs';
import { databaseContext } from './postgres/database.mjs';
import { exportAttendance, importAttendance } from '../shared/attendance-csv.mjs';

export async function attendancePresenceScenario(runtime) {
    const main = runtime.store.db, guildId = '823456789012345671', admin = { id: 'admin', username: 'admin', role: 'admin' };
    const w = await runtime.workspaces.create({ name: '입퇴실 수업', guildId }), db = (await runtime.workspaces.open(w.id)).db;
    let now = Date.parse('2026-09-19T01:00:00Z');
    const presence = createAttendancePresence(main, runtime.workspaces, { now: () => now });
    const put = (kind, value) => db.prepare('INSERT INTO lms_records(kind,id,data) VALUES(?,?,?)').run(kind, value.id, JSON.stringify(value));
    const student = { id: 'presence-student', username: 'presence.student', role: 'student', discordId: '923456789012345671' };
    await main.prepare("INSERT INTO lms_users(id,username,name,password_hash,discord_id,guild_id,created_at) VALUES(?,?,?,'unused',?,?,?)").run(student.id, student.username, '입퇴실 학생', student.discordId, guildId, now);
    await main.prepare('INSERT INTO lms_workspace_members VALUES(?,?,?,?)').run(w.id, student.id, 'student', now);
    await main.prepare('INSERT INTO lms_workspace_verifications VALUES(?,?,?,?,?)').run(w.id, student.id, guildId, student.discordId, now);
    await put('courses', { id: 'course', title: '입퇴실 과정' });
    await put('learners', { id: 'learner', courseId: 'course', name: '입퇴실 학생', discordId: student.discordId, status: '정상', team: '' });
    const selected = { courseId: 'course', date: '2026-09-19', period: 1 };
    const identity = { guildId, discordId: student.discordId };
    const mark = action => presence.mark(w.id, { ...selected, action }, student);
    const roster = () => runtime.attendance.view(w.id, selected, admin);
    const save = async (action, entries = []) => runtime.attendance.save(w.id, { ...selected, action, entries, requestId: randomUUID(), revision: (await roster()).revision }, admin);
    await assert.rejects(mark('in'), { status: 409 });
    assert.equal((await presence.view(w.id, student)).rounds.length, 0);
    await save('start');
    await assert.rejects(mark('out'), { status: 409 });
    await assert.rejects(presence.mark(w.id, { ...selected, action: 'in', checkInAt: 1 }, student));
    await assert.rejects(presence.mark(w.id, { ...selected, courseId: 'foreign', action: 'in' }, student), { status: 403 });
    const revision = (await roster()).revision, entered = await mark('in');
    assert.equal(entered.checkInAt, now);
    assert.equal(entered.checkOutAt, null);
    assert.equal(entered.checkInSource, 'web');
    assert.notEqual((await roster()).revision, revision);
    assert.equal((await roster()).rows[0].status, '미처리');
    await assert.rejects(save('close'), { status: 422 });
    now += 3600000;
    const repeated = await presence.discord({ ...identity, ...selected, action: 'in' }, true);
    assert.equal(repeated.checkInAt, entered.checkInAt);
    assert.equal(repeated.alreadyRecorded, true);
    const left = await presence.discord({ ...identity, ...selected, action: 'out' }, true);
    assert.equal(left.checkOutAt, now);
    assert.equal(left.checkOutSource, 'discord');
    assert.equal((await roster()).rows[0].status, '출석');
    assert.equal((await mark('out')).checkOutAt, left.checkOutAt);
    const csv = exportAttendance(selected, (await roster()).rows);
    assert.ok(csv.includes('2026-09-19 10:00:00'));
    assert.deepEqual(importAttendance(csv, selected, ['learner']).map(r => r.studentId), ['learner']);
    await save('save', [{ studentId: 'learner', status: '지각', reason: '멘토 확인' }]);
    await save('close');
    assert.equal((await presence.view(w.id, student)).history[0].status, '지각');
    assert.equal((await mark('out')).alreadyRecorded, true);
    selected.period = 2;
    await save('start');
    await save('save', [{ studentId: 'learner', status: '공결', reason: '승인된 사유' }]);
    if (db.dialect === 'postgres') {
        const values = await Promise.all([databaseContext(() => mark('in')), databaseContext(() => presence.discord({ ...identity, ...selected, action: 'in' }, true))]);
        assert.deepEqual(values.map(v => v.alreadyRecorded).sort(), [false, true]);
    } else await mark('in');
    now += 60000;
    await mark('out');
    assert.equal((await roster()).rows[0].status, '공결');
    await assert.rejects(presence.view(w.id, admin), { status: 403 });
    await main.prepare('DELETE FROM lms_workspace_verifications WHERE user_id=?').run(student.id);
    await assert.rejects(presence.view(w.id, student), { status: 403 });
    await main.prepare('INSERT INTO lms_workspace_verifications VALUES(?,?,?,?,?)').run(w.id, student.id, guildId, student.discordId, now);
    selected.period = 3;
    await save('start');
    now += 86400000;
    await assert.rejects(mark('in'), { status: 409 });
    await main.prepare('UPDATE lms_workspaces SET archived_at=? WHERE id=?').run(now, w.id);
    await assert.rejects(presence.discord(identity), { status: 403 });
}
