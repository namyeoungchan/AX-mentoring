import assert from 'node:assert/strict';

export async function learnerRemovalScenario(r, owner) {
    const w = await r.workspaces.create({ name: '수강생 삭제 검증' });
    const other = await r.workspaces.create({ name: '유지할 소속' });
    const db = (await r.workspaces.open(w.id)).db;
    const put = async (kind, value) => db.prepare('INSERT INTO lms_records(kind,id,data) VALUES(?,?,?)').run(kind, value.id, JSON.stringify(value));
    const student = (await r.auth.signup({ username: 'removal.student', name: '삭제 검증 학생', password: 'removal-test-password' }, () => {})).user;
    const discordId = '923456789012345678';
    await r.store.db.prepare('UPDATE lms_users SET discord_id=?,verified_at=? WHERE id=?').run(discordId, Date.now(), student.id);
    for (const id of [w.id, other.id]) await r.store.db.prepare('INSERT INTO lms_workspace_members VALUES(?,?,?,?)').run(id, student.id, 'student', Date.now());
    const learner = { id: 'manual-student', name: student.name, email: '', discordId, courseId: 'course', team: '1조', status: '정상', progress: 0, color: 'sage' };
    await put('courses', { id: 'course', title: '삭제 검증 과정' });
    await put('teams', { id: 'team', courseId: 'course', name: '1조', code: '1' });
    await put('learners', learner);
    await put('attendance', { id: 'attendance', studentId: learner.id, courseId: 'course', date: '2026-09-18', period: 1, status: '출석', reason: '확인' });
    const score = { id: 'score', studentId: learner.id, courseId: 'course', item: '평가', score: 80, maximum: 100 };
    await put('scores', score);
    const preview = () => r.admissions.learnerRemovalPlan(w.id, learner.id, owner);
    const remove = revision => r.admissions.removeLearner(w.id, learner.id, { revision }, owner);
    const plan = await preview();
    assert.equal(plan.accounts[0].id, student.id);
    assert.deepEqual(plan.history, { attendance: 1, scores: 1 });
    await assert.rejects(r.admissions.learnerRemovalPlan(w.id, learner.id, student), { status: 403 });
    await assert.rejects(r.admissions.removeLearner(w.id, learner.id, { revision: plan.revision }, student), { status: 403 });
    await db.prepare("UPDATE lms_records SET data=? WHERE kind='learners' AND id=?").run(JSON.stringify({ ...learner, name: '수정한 이름' }), learner.id);
    await assert.rejects(remove(plan.revision), { status: 409 });
    assert.equal(await r.workspaces.role(w.id, student), 'student');
    const current = await preview();
    await r.store.db.prepare("UPDATE lms_workspace_members SET role='instructor' WHERE workspace_id=? AND user_id=?").run(w.id, student.id);
    await assert.rejects(remove(current.revision), { status: 403 });
    await r.store.db.prepare("UPDATE lms_workspace_members SET role='student' WHERE workspace_id=? AND user_id=?").run(w.id, student.id);
    await r.workspaces.setArchived(w.id, true, owner);
    await assert.rejects(remove(current.revision), { status: 409 });
    await r.workspaces.setArchived(w.id, false, owner);
    assert.deepEqual(await remove(current.revision), { deleted: true });
    assert.deepEqual(await remove(current.revision), { deleted: false });
    const data = await r.workspaces.snapshot(w.id);
    assert.equal(data.learners.length, 0);
    assert.equal(data.removedLearners[0].name, '수정한 이름');
    assert.equal(data.attendance.length, 1);
    assert.equal(data.scores.length, 1);
    assert.equal(await r.workspaces.role(w.id, student), null);
    assert.equal(await r.workspaces.role(other.id, student), 'student');
    assert.ok(await r.store.db.prepare('SELECT id FROM lms_users WHERE id=?').get(student.id));
    const selection = { courseId: 'course', date: '2026-09-18', period: 1 };
    assert.equal((await r.attendance.view(w.id, selection, owner)).rows[0].name, '수정한 이름');
    assert.equal((await r.attendance.view(w.id, { ...selection, period: 2 }, owner)).rows.length, 0);
    const mutate = async (kind, value) => r.workspaces.mutate(w.id, { revision: (await r.workspaces.snapshot(w.id)).revision, changes: [{ kind, value }] }, owner.username);
    await assert.rejects(mutate('learners', learner), { status: 409 });
    await assert.rejects(mutate('scores', { ...score, id: 'new-score' }), { status: 422 });
    await mutate('scores', { ...score, score: 90 });
    assert.equal((await r.workspaces.snapshot(w.id)).scores[0].score, 90);
    // A direct learner without a linked account remains removable, even with reused contact details.
    await mutate('learners', { ...learner, id: 'replacement' });
    const replacement = await r.admissions.learnerRemovalPlan(w.id, 'replacement', owner);
    assert.equal(replacement.accounts.length, 0);
    await r.admissions.removeLearner(w.id, 'replacement', { revision: replacement.revision }, owner);
    assert.equal((await r.workspaces.snapshot(w.id)).removedLearners.length, 2);
}
