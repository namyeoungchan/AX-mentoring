import assert from 'node:assert/strict';
import { randomUUID } from 'node:crypto';
import { createAnnouncements } from './announcements.mjs';

export async function announcementsScenario(r) {
    const admin = { id: 'admin', role: 'admin', username: 'announcement.admin' };
    const w = await r.workspaces.create({ name: '배너 팝업 검증' });
    const db = (await r.workspaces.open(w.id)).db;
    const makeUser = async (name, role) => {
        const user = (await r.auth.signup({ username: `announcement.${name}`, name, password: 'test-password-12345' }, () => {})).user;
        await r.store.db.prepare('INSERT INTO lms_workspace_members VALUES(?,?,?,1)').run(w.id, user.id, role);
        return user;
    };
    const manager = await makeUser('manager', 'admin');
    const mentor = await makeUser('mentor', 'instructor');
    const student = await makeUser('student', 'student');
    const service = createAnnouncements(r.workspaces, { now: () => Date.parse('2026-11-18T09:00:00+09:00') });
    const image = 'data:image/png;base64,iVBORw0KGgo=';
    const banner = { id: randomUUID(), placement: 'banner', title: '11월 특강 안내', body: '이번 주 금요일 특강이 열립니다.', image, linkUrl: 'https://example.com/event', linkLabel: '자세히 보기', audience: ['student', 'instructor'], startDate: '2026-11-01', endDate: '2026-11-30', enabled: true };
    const popup = { ...banner, id: randomUUID(), placement: 'popup', title: '멘토 전용 공지', image: '', linkUrl: '', linkLabel: '', audience: ['instructor'], startDate: '', endDate: '' };
    await assert.rejects(service.list(w.id, mentor), { status: 403 });
    await assert.rejects(service.create(w.id, banner, mentor), { status: 403 });
    await assert.rejects(service.create(w.id, banner, student), { status: 403 });
    await assert.rejects(service.create(w.id, { ...banner, linkUrl: 'javascript:alert(1)' }, manager));
    await assert.rejects(service.create(w.id, { ...banner, image: 'data:image/svg+xml;base64,PHN2Zz4=' }, manager));
    await assert.rejects(service.create(w.id, { ...banner, audience: [] }, manager));
    await assert.rejects(service.create(w.id, { ...banner, endDate: '2026-10-01' }, manager), { status: 422 });
    await assert.rejects(service.create(w.id, { ...banner, linkUrl: '' }, manager), { status: 422 });
    await assert.rejects(service.create(w.id, { ...banner, createdBy: student.id }, manager));
    const created = await service.create(w.id, banner, manager);
    assert.equal(created.revision, 1);
    assert.equal((await service.create(w.id, banner, manager)).id, created.id, 'retry does not create a second banner');
    await assert.rejects(service.create(w.id, { ...banner, title: '다른 내용' }, manager), { status: 409 });
    await service.create(w.id, popup, admin);
    await service.create(w.id, { ...banner, id: randomUUID(), title: '지난 배너', startDate: '2026-10-01', endDate: '2026-10-31' }, manager);
    await service.create(w.id, { ...banner, id: randomUUID(), title: '꺼둔 배너', enabled: false }, manager);
    await service.create(w.id, { ...banner, id: randomUUID(), title: '예정 배너', startDate: '2026-12-01', endDate: '' }, manager);
    assert.equal((await service.list(w.id, manager)).announcements.length, 5);
    const forStudent = await service.active(w.id, student);
    assert.deepEqual(forStudent.banners.map(v => v.title), ['11월 특강 안내']);
    assert.deepEqual(forStudent.popups, []);
    assert.equal(forStudent.banners[0].createdBy, undefined, 'members only receive display fields');
    const forMentor = await service.active(w.id, mentor);
    assert.deepEqual([forMentor.banners.length, forMentor.popups.map(v => v.title)], [1, ['멘토 전용 공지']]);
    assert.deepEqual(await service.active(w.id, manager), { banners: [], popups: [] });
    const { id: _id, ...fields } = banner;
    await assert.rejects(service.edit(w.id, created.id, { ...fields, revision: 1 }, mentor), { status: 403 });
    const changed = await service.edit(w.id, created.id, { ...fields, revision: 1, audience: ['student'] }, manager);
    assert.equal(changed.revision, 2);
    assert.equal((await service.active(w.id, mentor)).banners.length, 0);
    await assert.rejects(service.edit(w.id, created.id, { ...fields, revision: 1 }, manager), { status: 409 });
    await assert.rejects(service.remove(w.id, created.id, { revision: 1 }, manager), { status: 409 });
    await assert.rejects(service.remove(w.id, created.id, { revision: 2 }, student), { status: 403 });
    await service.remove(w.id, created.id, { revision: 2 }, manager);
    await assert.rejects(service.remove(w.id, created.id, { revision: 2 }, manager), { status: 404 });
    const foreign = await r.workspaces.create({ name: '다른 워크스페이스' });
    await assert.rejects(service.active(foreign.id, student), { status: 403 });
    await assert.rejects(service.edit(foreign.id, changed.id, { ...fields, revision: 2 }, admin), { status: 404 });
    const audits = await db.prepare("SELECT before_json,after_json FROM lms_audit WHERE action LIKE 'announcement.%'").all();
    assert.equal(audits.length, 7);
    assert.ok(audits.every(row => !`${row.before_json}${row.after_json}`.includes('base64')), 'audit log omits image bytes');
    await r.workspaces.setArchived(w.id, true, admin);
    assert.equal((await service.list(w.id, manager)).canEdit, false);
    await assert.rejects(service.create(w.id, { ...popup, id: randomUUID() }, manager), { status: 409 });
    return { workspaceId: w.id, announcements: 4 };
}
