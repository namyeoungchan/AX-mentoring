import assert from 'node:assert/strict';
import { randomUUID } from 'node:crypto';

export async function accountRoleScenario({ store, auth, workspaces, staff }, administrator) {
    const db = store.db;
    const workspace = await workspaces.create({ name: 'Role switching', guildId: '932456789012345678' });
    const other = await workspaces.create({ name: 'Other role workspace' });
    const groups = await staff.setupGroups(workspace.id, { count: 2, revision: (await staff.groups(workspace.id)).revision }, administrator);
    const input = { username: 'role.switcher', name: 'Role tester', password: 'test-only-role-password', discordId: '933456789012345678' };
    const login = await auth.signup(input, () => {}), user = login.user;
    await db.prepare('INSERT INTO lms_workspace_members VALUES(?,?,?,?)').run(other.id, user.id, 'instructor', Date.now());
    const originalHash = (await db.prepare('SELECT password_hash FROM lms_users WHERE id=?').get(user.id)).password_hash;
    const pending = await workspaces.invite(workspace.id, { username: input.username, role: 'instructor' }, administrator);
    const body = (role, expectedRole, extra = {}) => ({ role, expectedRole, ...extra });
    const change = value => staff.changeAccountRole(workspace.id, user.id, value, administrator);
    assert.equal((await staff.accountRole(workspace.id, user.id, administrator)).role, null);
    await assert.rejects(staff.accountRole(workspace.id, user.id, { ...user, role: 'admin', isSuperAdmin: true }), { status: 403 });
    await assert.rejects(staff.changeAccountRole(workspace.id, administrator.id, body('student', null), administrator), { status: 403 });
    await assert.rejects(change(body('superadmin', null)), { name: 'ZodError' });
    await assert.rejects(change(body('instructor', null, { mentorType: 'group', teamIds: ['foreign'] })), { status: 422 });
    assert.ok(await auth.session(login.token));
    assert.equal(await workspaces.role(workspace.id, user), null);
    await change(body('admin', null));
    assert.equal(await auth.session(login.token), null);
    assert.equal(await workspaces.role(workspace.id, user), 'admin');
    assert.equal(await workspaces.role(other.id, user), 'instructor');
    await assert.rejects(workspaces.previewInvitation(pending.token), { status: 410 });
    await assert.rejects(staff.changeAccountRole(workspace.id, user.id, body('student', 'admin'), user), { status: 403 });
    await assert.rejects(change(body('student', null)), { status: 409 });
    await change(body('instructor', 'admin'));
    assert.equal((await staff.accountRole(workspace.id, user.id, administrator)).mentorType, 'main');
    const target = (await workspaces.open(workspace.id)).db;
    assert.equal(await target.prepare('SELECT id FROM mentors WHERE discord_id=?').get(input.discordId), undefined);
    await db.prepare('INSERT INTO lms_workspace_verifications VALUES(?,?,?,?,?)').run(workspace.id, user.id, workspace.guildIds[0], input.discordId, Date.now());
    await db.prepare("INSERT INTO lms_admissions(id,workspace_id,user_id,state,created_at,purpose,team_id) VALUES(?,?,?,'joined',?,'student',?)").run(randomUUID(), workspace.id, user.id, Date.now(), groups.teams[0].id);
    await change(body('instructor', 'instructor', { mentorType: 'group', teamIds: [groups.teams[0].id] }));
    assert.deepEqual((await workspaces.teaching(workspace.id, user)).teams.map(team => team.id), [groups.teams[0].id]);
    const mentor = await target.prepare('SELECT id,is_active FROM mentors WHERE discord_id=?').get(input.discordId);
    assert.equal(mentor.is_active, 1);
    await target.prepare("INSERT INTO slots(mentor_id,start_time,end_time,label) VALUES(?,'2030-01-01T12:00:00','2030-01-01T13:00:00','Role test slot')").run(mentor.id);
    const session = await auth.login({ username: input.username, password: input.password });
    await change(body('student', 'instructor'));
    assert.equal(await auth.session(session.token), null);
    assert.equal(await workspaces.role(workspace.id, user), 'student');
    assert.equal((await target.prepare('SELECT is_active FROM mentors WHERE id=?').get(mentor.id)).is_active, 0);
    assert.equal((await target.prepare('SELECT is_active FROM slots WHERE mentor_id=?').get(mentor.id)).is_active, 0);
    assert.equal(await db.prepare('SELECT 1 FROM lms_mentor_scopes WHERE workspace_id=? AND subject_id=?').get(workspace.id, user.id), undefined);
    assert.equal((await db.prepare('SELECT team_id,purpose FROM lms_admissions WHERE workspace_id=? AND user_id=?').get(workspace.id, user.id)).team_id, groups.teams[0].id);
    assert.equal((await db.prepare('SELECT purpose FROM lms_admissions WHERE workspace_id=? AND user_id=?').get(workspace.id, user.id)).purpose, 'student');
    assert.ok(await db.prepare('SELECT 1 FROM lms_workspace_verifications WHERE workspace_id=? AND user_id=?').get(workspace.id, user.id));
    assert.equal((await db.prepare('SELECT password_hash FROM lms_users WHERE id=?').get(user.id)).password_hash, originalHash);
    const relogin = await auth.login({ username: input.username, password: input.password });
    assert.equal(relogin.user.role, 'student');
    assert.equal(relogin.user.isSuperAdmin, false);
    assert.equal((await auth.accounts(administrator)).accounts.find(row => row.id === user.id).memberships.find(row => row.workspaceId === workspace.id).role, 'student');
    assert.equal((await db.prepare("SELECT COUNT(*) AS n FROM lms_audit WHERE action='account.workspace-role'").get()).n, 4);
    await workspaces.setArchived(workspace.id, true, administrator);
    await assert.rejects(change(body('admin', 'student')), { status: 409 });
    assert.equal(await workspaces.role(other.id, user), 'instructor');
}
