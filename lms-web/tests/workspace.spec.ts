test('desktop, tablet and mobile layouts have no page overflow', async ({ page }) => {
  await page.goto('/?demo=1')
  for (const [width, height] of [[1440, 1000], [820, 1180], [390, 844], [360, 800]]) {
    await page.setViewportSize({ width, height })
    await expect(page.getByRole('heading', { name: '운영 대시보드' })).toBeVisible()
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBeTruthy()
    await page.screenshot({ path: `test-results/dashboard-${width}.png`, fullPage: true, animations: 'disabled' })
  }
  await page.getByRole('button', { name: '메뉴 열기' }).click()
  await page.getByRole('navigation').getByRole('button', { name: '출결 관리' }).click()
  await expect(page.getByRole('heading', { name: '출결 관리', exact: true })).toBeVisible()
  await expect(page.getByRole('button', { name: '메뉴 닫기' })).not.toBeVisible()
})
